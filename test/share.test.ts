describe("share credentials", () => {
  const s3 = { bucket: "b", prefix: "p/", expiresInDays: 7 };
  const share = { s3 };
  let dir: string;
  const fileIn = (name = "share-credentials.json") => path.join(dir, name);
  const write = (content: unknown, mode = 0o600, name?: string) => {
    fs.writeFileSync(fileIn(name), typeof content === "string" ? content : JSON.stringify(content), { mode });
    fs.chmodSync(fileIn(name), mode);
  };
  const FILE_CREDS = { accessKeyId: "AKFILE", secretAccessKey: "SKFILE", sessionToken: "TOKFILE" };

  beforeEach(() => {
    dir = fs.mkdtempSync(path.join(os.tmpdir(), "tpc-share-creds-"));
  });
  afterEach(() => fs.rmSync(dir, { recursive: true, force: true }));

  test("without environment credentials the default file next to the config is used", () => {
    write(FILE_CREDS);
    expect(resolveShareCredentials(s3, { env: {}, configDir: dir })).toEqual({ ok: true, credentials: { source: "file", ...FILE_CREDS } });
    write({ accessKeyId: "A", secretAccessKey: "S" });
    expect(resolveShareCredentials(s3, { env: {}, configDir: dir })).toEqual({ ok: true, credentials: { source: "file", accessKeyId: "A", secretAccessKey: "S" } });
  });

  test("credentialsFile overrides the default location, and ~ means the home directory", () => {
    write(FILE_CREDS, 0o600, "custom.json");
    expect(resolveShareCredentials({ ...s3, credentialsFile: fileIn("custom.json") }, { env: {}, configDir: "/nowhere" })).toMatchObject({ ok: true, credentials: { accessKeyId: "AKFILE" } });
    const home = fs.mkdtempSync(path.join(os.tmpdir(), "tpc-share-home-"));
    try {
      fs.writeFileSync(path.join(home, "creds.json"), JSON.stringify(FILE_CREDS), { mode: 0o600 });
      expect(resolveShareCredentials({ ...s3, credentialsFile: "~/creds.json" }, { env: {}, configDir: "/nowhere", home })).toMatchObject({ ok: true, credentials: { secretAccessKey: "SKFILE" } });
    } finally {
      fs.rmSync(home, { recursive: true, force: true });
    }
  });

  test("environment credentials win over the file, and only a complete pair counts", () => {
    write(FILE_CREDS);
    expect(resolveShareCredentials(s3, { env: { S3_ACCESS_KEY_ID: "a", S3_SECRET_ACCESS_KEY: "b" }, configDir: dir })).toEqual({ ok: true, credentials: { source: "env" } });
    expect(resolveShareCredentials(s3, { env: { AWS_ACCESS_KEY_ID: "a", AWS_SECRET_ACCESS_KEY: "b" }, configDir: dir })).toEqual({ ok: true, credentials: { source: "env" } });
    expect(resolveShareCredentials(s3, { env: { S3_ACCESS_KEY_ID: "a" }, configDir: dir })).toMatchObject({ ok: true, credentials: { source: "file" } });
  });

  test("a credentials file that group or others can access is refused", () => {
    for (const mode of [0o644, 0o640, 0o604]) {
      write(FILE_CREDS, mode);
      const out = resolveShareCredentials(s3, { env: {}, configDir: dir });
      expect(out.ok).toBe(false);
      if (!out.ok) {
        expect(out.problem).toContain(fileIn());
        expect(out.problem).toContain("chmod 600");
      }
    }
    write(FILE_CREDS, 0o400);
    expect(resolveShareCredentials(s3, { env: {}, configDir: dir }).ok).toBe(true);
  });

  test("missing or malformed credentials name the file that would be read", () => {
    const missing = resolveShareCredentials(s3, { env: {}, configDir: dir });
    expect(missing).toEqual({
      ok: false,
      problem: `sharing is not configured: no S3 credentials (set S3_ACCESS_KEY_ID/S3_SECRET_ACCESS_KEY or create ${fileIn()} with mode 600)`,
    });
    write("{ not json");
    const broken = resolveShareCredentials(s3, { env: {}, configDir: dir });
    expect(broken.ok).toBe(false);
    if (!broken.ok) expect(broken.problem).toContain(fileIn());
    write({ accessKeyId: "A" });
    expect(resolveShareCredentials(s3, { env: {}, configDir: dir }).ok).toBe(false);
  });

  test("the config rejects a relative credentialsFile", () => {
    const parse = (credentialsFile: string) => ConfigSchema.safeParse({ ...config, share: { s3: { bucket: "b", credentialsFile } } }).success;
    expect(parse("/abs/creds.json")).toBe(true);
    expect(parse("~/creds.json")).toBe(true);
    expect(parse("creds.json")).toBe(false);
  });

  test("shareStatus reports the problem instead of configured, and shareRun refuses with it before uploading", async () => {
    write(FILE_CREDS, 0o644);
    const status = shareStatus(share, { env: {}, configDir: dir });
    expect(status).toMatchObject({ configured: false, provider: "s3", expiresInDays: 7 });
    expect(status.problem).toContain("chmod 600");
    const run = makeStoredRun({ testKey: uniqueTest(), at: 0 });
    const uploads: string[] = [];
    const client: ShareClient = { write: async (key) => uploads.push(key), presign: (key) => key };
    const err = await shareRun(run.id, { share, client, env: {}, configDir: dir }).catch((e: unknown) => e);
    expect(err).toBeInstanceOf(HttpError);
    expect((err as HttpError).status).toBe(400);
    expect((err as HttpError).message).toBe(status.problem!);
    expect(uploads).toEqual([]);
    write(FILE_CREDS);
    expect(shareStatus(share, { env: {}, configDir: dir })).toEqual({ configured: true, provider: "s3", expiresInDays: 7, problem: null });
  });
});
